std::vector<std::uint8_t> hx(const char* hex)
{
    std::vector<std::uint8_t> v;
    if (hex && !fromHex(hex, v)) {
        std::printf("\n    BAD HEX: %s\n", hex);
        std::abort();
    }
    return v;
}

SecretKey secretOf(const char* hex)
{
    const auto v = hx(hex);
    SecretKey k{};
    if (v.size() == k.size()) std::memcpy(k.data(), v.data(), k.size());
    return k;
}

PublicKey publicOf(const char* hex)
{
    const auto v = hx(hex);
    PublicKey k{};
    if (v.size() == k.size()) std::memcpy(k.data(), v.data(), k.size());
    return k;
}

std::size_t handshakeMessageCount(const char* protocolName)
{
    // XX is three messages, IK is two. Read from the name so a vector for some
    // other pattern cannot be silently mis-driven.
    return std::strstr(protocolName, "_IK_") ? 2u : 3u;
}

