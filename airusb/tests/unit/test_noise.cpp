// P2.4 — the Noise handshake, against somebody else's implementation.
//
// The first test in this file is the one that matters. A Noise implementation
// that only ever talks to itself agrees with itself perfectly while being wrong
// in ways no round trip can reveal: HKDF arguments swapped, BLAKE2s's native
// keyed mode used where HMAC is specified, the nonce encoded big-endian, the
// ciphertext hashed instead of the plaintext. Every one of those produces a
// self-consistent private protocol with none of the review the real one has had.
//
// tests/vectors/NoiseVectors.h holds the official cross-implementation vectors
// for exactly the two protocols AirUSB speaks, generated by an independent
// implementation. Matching them message by message — including the final
// handshake hash, which is what the SAS is derived from — is what makes this a
// Noise implementation rather than something Noise-shaped.
//
// Everything after that tests the properties the vectors cannot: that tampering
// is caught, that a forged record does not desynchronise the stream, that the
// prologue is really bound, and that a truncated handshake message is refused
// rather than read past.

#include "../TestHarness.h"
#include "../vectors/NoiseVectors.h"
